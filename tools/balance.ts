/**
 * Headless balance report: N AI-vs-AI matches per difficulty (win rate vs the
 * level below, stalls, length) and a mirror-level matchup table.
 * Usage: pnpm tsx tools/balance.ts [matchesPerLevel=1000] [perPair=6]
 * Writes docs/BALANCE.md.
 */
import { writeFileSync } from 'node:fs';
import { CHARACTERS } from '@/data/characters';
import { levelReport, matchupTable } from '@/ai/batch';
import { AI_LEVEL_NAMES } from '@/ai/LayeredAI';

const perLevel = parseInt(process.argv[2] ?? '1000', 10);
const perPair = parseInt(process.argv[3] ?? '6', 10);
const roster = Object.values(CHARACTERS).filter((c) => c.id !== 'greybox');
const t0 = Date.now();
const lines: string[] = ['# Balance report', '', `Generated by tools/balance.ts (${perLevel} matches per level, ${perPair} per pair). Best-of-3, 40 s rounds.`, ''];
lines.push('## Difficulty ladder', '', '| Level | Matches | Win rate vs level below | Stalls | Avg length (s) |', '|---|---|---|---|---|');
for (let level = 0; level < 5; level++) {
  const r = levelReport(roster, level, perLevel, 5000 + level * 10000);
  lines.push(`| ${level} ${AI_LEVEL_NAMES[level]} | ${r.matches} | ${level === 0 ? '—' : (r.winRateVsLower * 100).toFixed(1) + '%'} | ${r.stalls} | ${(r.avgFrames / 60).toFixed(1)} |`);
  console.info(`level ${level}: win ${(r.winRateVsLower * 100).toFixed(1)}% stalls ${r.stalls} avg ${(r.avgFrames / 60).toFixed(1)}s`);
}
lines.push('', '## Matchups (Hard vs Hard, P1 win rate)', '');
const table = matchupTable(roster, 3, perPair);
const ids = roster.map((c) => c.id);
lines.push(`| | ${ids.join(' | ')} |`, `|---|${ids.map(() => '---').join('|')}|`);
const overall = new Map<string, { w: number; n: number }>();
for (const a of ids) {
  const row = ids.map((b) => {
    if (a === b) return '—';
    const cell = table.find((c) => c.p1 === a && c.p2 === b);
    if (!cell) return '?';
    const o = overall.get(a) ?? { w: 0, n: 0 };
    o.w += cell.p1WinRate * cell.n; o.n += cell.n; overall.set(a, o);
    const ob = overall.get(b) ?? { w: 0, n: 0 };
    ob.w += (1 - cell.p1WinRate) * cell.n; ob.n += cell.n; overall.set(b, ob);
    return `${(cell.p1WinRate * 100).toFixed(0)}%`;
  });
  lines.push(`| ${a} | ${row.join(' | ')} |`);
}
lines.push('', '## Overall win rate by character (Hard mirror level, both sides of every pairing)', '', '| Character | Win rate |', '|---|---|');
for (const a of ids) { const o = overall.get(a); lines.push(`| ${a} | ${o && o.n ? ((o.w / o.n) * 100).toFixed(1) + '%' : '—'} |`); }
lines.push('', `Run time: ${((Date.now() - t0) / 1000).toFixed(0)} s.`);
writeFileSync('docs/BALANCE.md', lines.join('\n') + '\n');
console.info('wrote docs/BALANCE.md');
